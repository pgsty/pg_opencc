#!/usr/bin/env python3
"""Generate a C source file that embeds OpenCC configs and dictionaries.

The extension never reads OpenCC data from the filesystem at runtime: every
built-in configuration (JSON) and every dictionary it references (.ocd2,
compiled by the vendored OpenCC build on the build host) is compiled into
opencc.so as a read-only byte array.  This keeps results identical wherever
the same extension version is installed.

Usage:
  embed_resources.py --config-dir DIR --dict-dir DIR --version-cmake FILE \
                     --output FILE CONFIG [CONFIG ...]
"""

import argparse
import hashlib
import json
import os
import re
import sys


def strip_jsonc(text):
    """Remove // and /* */ comments and trailing commas (OpenCC configs are JSONC)."""
    out, i, n, in_str = [], 0, len(text), False
    while i < n:
        c = text[i]
        if in_str:
            out.append(c)
            if c == "\\" and i + 1 < n:
                out.append(text[i + 1])
                i += 2
                continue
            if c == '"':
                in_str = False
            i += 1
        elif c == '"':
            in_str = True
            out.append(c)
            i += 1
        elif text.startswith("//", i):
            while i < n and text[i] != "\n":
                i += 1
        elif text.startswith("/*", i):
            end = text.find("*/", i + 2)
            i = n if end < 0 else end + 2
        else:
            out.append(c)
            i += 1
    return re.sub(r",(\s*[}\]])", r"\1", "".join(out))


def referenced_files(node, found):
    if isinstance(node, dict):
        if "file" in node and isinstance(node["file"], str):
            found.add(node["file"])
        for value in node.values():
            referenced_files(value, found)
    elif isinstance(node, list):
        for value in node:
            referenced_files(value, found)


def opencc_version(path):
    with open(path, encoding="utf-8") as f:
        text = f.read()
    parts = []
    for key in ("MAJOR", "MINOR", "REVISION"):
        m = re.search(r"set\(_OPENCC_FALLBACK_%s\s+(\d+)\)" % key, text)
        if not m:
            sys.exit("cannot find _OPENCC_FALLBACK_%s in %s" % (key, path))
        parts.append(m.group(1))
    return ".".join(parts)


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config-dir", required=True)
    ap.add_argument("--dict-dir", required=True)
    ap.add_argument("--version-cmake", required=True)
    ap.add_argument("--output", required=True)
    ap.add_argument("configs", nargs="+")
    args = ap.parse_args()

    resources = {}  # name -> bytes
    dicts = set()
    for name in args.configs:
        path = os.path.join(args.config_dir, name + ".json")
        with open(path, "rb") as f:
            raw = f.read()
        referenced_files(json.loads(strip_jsonc(raw.decode("utf-8"))), dicts)
        resources[name + ".json"] = raw
    for name in sorted(dicts):
        path = os.path.join(args.dict_dir, name)
        if not os.path.isfile(path):
            sys.exit("dictionary %s referenced by a config was not built (%s)" % (name, path))
        with open(path, "rb") as f:
            resources[name] = f.read()

    digest = hashlib.sha256()
    for name in sorted(resources):
        data = resources[name]
        digest.update(name.encode("utf-8") + b"\0" + str(len(data)).encode("ascii") + b"\0")
        digest.update(data)

    lines = [
        "/* Generated by tools/embed_resources.py -- do not edit. */",
        "#include <stddef.h>",
        '#include "opencc_resources.h"',
        "",
    ]
    names = sorted(resources)
    for idx, name in enumerate(names):
        data = resources[name]
        lines.append("/* %s (%d bytes) */" % (name, len(data)))
        lines.append("static const unsigned char res_%d[%d] = {" % (idx, max(len(data), 1)))
        for off in range(0, len(data), 24):
            lines.append(",".join("%d" % b for b in data[off:off + 24]) + ",")
        if not data:
            lines.append("0")
        lines.append("};")
    lines.append("")
    lines.append("const ocpg_resource ocpg_resources[] = {")
    for idx, name in enumerate(names):
        lines.append("  {%s, res_%d, %d}," % (c_string(name), idx, len(resources[name])))
    lines.append("};")
    lines.append("const size_t ocpg_resource_count = %d;" % len(names))
    lines.append("const char ocpg_opencc_version[] = %s;" % c_string(opencc_version(args.version_cmake)))
    lines.append("const char ocpg_resource_digest[] = %s;" % c_string("sha256:" + digest.hexdigest()))
    lines.append("")

    tmp = args.output + ".tmp"
    with open(tmp, "w", encoding="ascii") as f:
        f.write("\n".join(lines))
    os.replace(tmp, args.output)
    total = sum(len(v) for v in resources.values())
    print("embedded %d resources, %d bytes, sha256:%s" % (len(names), total, digest.hexdigest()))


if __name__ == "__main__":
    main()
