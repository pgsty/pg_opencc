#!/usr/bin/env python3
"""Turn OpenCC's own golden test cases into a pg_regress test.

Reads vendor/opencc/test/testcases/testcases.json (JSON with trailing commas)
and writes test/sql/opencc_upstream.sql, which checks every case through
opencc.convert().  Re-run after updating the vendored OpenCC.
"""

import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "vendor", "opencc", "test", "testcases", "testcases.json")
DST = os.path.join(ROOT, "test", "sql", "opencc_upstream.sql")


def quote(s):
    return "'" + s.replace("'", "''") + "'"


def main():
    with open(SRC, encoding="utf-8") as f:
        cases = json.loads(re.sub(r",(\s*[}\]])", r"\1", f.read()))["cases"]
    rows = []
    for case in cases:
        for config, expected in sorted(case["expected"].items()):
            rows.append("(%s, %s, %s, %s)" % (quote(case["id"]), quote(config),
                                              quote(case["input"]), quote(expected)))
    with open(DST, "w", encoding="utf-8") as f:
        f.write("-- Generated by tools/gen_upstream_test.py from OpenCC's test/testcases/testcases.json.\n")
        f.write("-- Every upstream golden case must convert exactly as OpenCC itself does.\n")
        f.write("CREATE TEMP TABLE upstream_case (id text, config text, input text, expected text);\n")
        f.write("INSERT INTO upstream_case VALUES\n")
        f.write(",\n".join(rows))
        f.write(";\n\n")
        f.write("SELECT count(*) AS cases, count(DISTINCT config) AS configs FROM upstream_case;\n\n")
        f.write("SELECT config, count(*) AS cases,\n"
                "       count(*) FILTER (WHERE opencc.convert(input, config) <> expected) AS failures\n"
                "  FROM upstream_case GROUP BY config ORDER BY config;\n\n")
        f.write("SELECT id, config, input, expected, opencc.convert(input, config) AS actual\n"
                "  FROM upstream_case\n"
                " WHERE opencc.convert(input, config) <> expected\n"
                " ORDER BY id, config;\n")
    print("wrote %d cases to %s" % (len(rows), os.path.relpath(DST, ROOT)), file=sys.stderr)


if __name__ == "__main__":
    main()
